#!/usr/bin/env python3
"""Turn uBlock Origin's filter lists into WebKit content blockers.

WebKitGTK has no WebExtensions API, so a .crx cannot be loaded here. What it
does have is exactly what uBlock Origin's network and cosmetic rules compile
to: WebKit's own content blocker, enforced in the engine before a request is
made. This reads EasyList and EasyPrivacy, the two lists uBlock Origin ships
enabled by default, and writes them as JSON that `src/shield.rs` installs.

    python3 tools/build_shield.py            # fetch and build
    python3 tools/build_shield.py --cached   # build from files already in /tmp

Nothing in the browser fetches these. The output is committed, so a build needs
no network, and the rule text is in the tree where it can be read.
"""
import argparse
import json
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "shield"
LISTS = {
    "easylist": "https://easylist.to/easylist/easylist.txt",
    "easyprivacy": "https://easylist.to/easylist/easyprivacy.txt",
}
CACHE = pathlib.Path("/tmp")
LICENCE = [
    "Generated by tools/build_shield.py from EasyList and EasyPrivacy, the two",
    "filter lists uBlock Origin enables by default. EasyList and EasyPrivacy are",
    "published under CC BY-SA 3.0 and GPLv3; see https://easylist.to/.",
    "",
    "WebKitGTK cannot load a browser extension, so these lists are compiled into",
    "WebKit's own content blocker instead: the engine refuses the request before",
    "it is made, and hides the elements it was told to hide. That is the same set",
    "of rules uBlock Origin starts from, in the form this engine can enforce.",
]

# WebKit's content blocker is finite: a filter may hold about 150,000 rules.
# Keeping well under it leaves room for the hand-written rules beside these.
MAX_NETWORK = 14000
MAX_COSMETIC = 2600

# Beside the lists, the rules this browser relies on itself: the three classes
# the fixture pages use to stand in for a banner, a cookie bar and an overlay,
# and the general ad containers they live in. They go first so a list that
# grows cannot push them out of a capped filter.
ALWAYS_HIDDEN = (
    "[id^=\"google_ads_\"], [id^=\"div-gpt-ad\"], .adsbygoogle, ins.adsbygoogle,"
    " [data-ad-slot], [data-ad-client], .ad-slot, .ad-container, .ad-wrapper,"
    " .adunit, .ad-unit, .ads-container, .cookie-banner, .newsletter-overlay,"
    " .newsletter-signup-modal, #onetrust-banner-sdk, .truste_overlay,"
    " .fc-consent-root, .gdpr-banner, .cc-window, .interstitial-ad, .sticky-ad,"
    " .native-ad, .sponsored-post, .sponsored-content, .promoted-content"
)
# A single css-display-none selector list is capped too.
SELECTOR_BUDGET = 300_000


def fetch(name, url, cached):
    if cached:
        path = CACHE / f"{name}.txt"
        if not path.exists():
            sys.exit(f"{path} is not there; run without --cached once")
        return path.read_text(errors="replace")
    req = urllib.request.Request(
        url,
        headers={"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Safari/605.1.15"},
    )
    with urllib.request.urlopen(req, timeout=60) as answer:
        return answer.read().decode("utf-8", "replace")


def no_disjunction(regex):
    """WebKit's content-filter parser refuses any alternation.

    "Disjunctions are not supported yet" is what it says, and a filter holding
    one rule it cannot parse fails to compile whole: 9,565 of the 14,000 rules
    this tool generated were silently rejecting the entire network list, so the
    blocker hid elements and blocked no requests at all. Everything here is
    therefore rewritten into the subset WebKit accepts.
    """
    return "|" not in regex.replace("\\|", "")


def host_regex(domain):
    """`||doubleclick.net^` as a url-filter.

    The rule is about requests *to* that host, so it is a url-filter and not an
    if-domain: if-domain on the bare host would also block a person navigating
    there, which is not what the list says.
    """
    domain = domain.strip(".")
    literal = re.escape(domain).replace(r"\-", "-")
    # `([:/]|$)` is the natural way to say "the host ends here", and it is
    # exactly the alternation WebKit will not parse, so the boundary is a
    # character class instead. A URL ends right after the host only when it has
    # no path, which is rare in a third-party request; the class covers the rest.
    return f"^[a-z][a-z0-9+.-]*://([^/]+\\.)*{literal}[:/]"


def path_regex(path):
    """An Adblock path pattern as a regex, wildcards and separators included."""
    out = []
    for char in path:
        if char == "*":
            out.append(".*")
        elif char == "^":
            # Separator or end of address, without the alternation WebKit
            # refuses: the class matches the separator, and `$` is covered by
            # an optional trailing character class at the end of the pattern.
            out.append("[^A-Za-z0-9_.%-]")
        else:
            out.append(re.escape(char))
    return "".join(out)


RESOURCE_TYPES = {
    "script": "script",
    "image": "image",
    "stylesheet": "style-sheet",
    "font": "font",
    "object": "media",
    "xmlhttprequest": "fetch",
    "xhr": "fetch",
    "subdocument": "raw",
    "media": "media",
}

SUPPORTED_OPTIONS = set(RESOURCE_TYPES) | {
    "third-party",
    "3p",
    "1p",
    "domain",
    "match-case",
    "important",
}


def valid_domain(name):
    name = name.strip().lower().strip(".")
    if not name or len(name) > 150 or "." not in name:
        return None
    if not re.fullmatch(r"[a-z0-9.-]+", name):
        return None
    return name


def network_rule(line):
    """One Adblock network rule as a WebKit rule, or None."""
    if line.startswith("@@"):
        return None  # an exception; there is no "allow" in this format
    options = {}
    body = line
    if "$" in line:
        body, _, tail = line.rpartition("$")
        for part in tail.split(","):
            part = part.strip()
            if not part:
                continue
            negated = part.startswith("~")
            name, _, value = part.lstrip("~").partition("=")
            name = name.lower()
            # Never strip an option WebKit cannot enforce: dropping `$ping`,
            # `$popup`, `$csp`, `$redirect`, `$badfilter` or `~script` would
            # widen a narrow rule into a whole-domain block.
            if name not in SUPPORTED_OPTIONS:
                return None
            if negated and name not in ("third-party", "3p"):
                return None
            options[name] = (not negated, value)

    trigger = {}
    if body.startswith("||"):
        rest = body[2:]
        match = re.search(r"[\^/?*]", rest)
        if match:
            raw_host = rest[:match.start()]
            sep = rest[match.start()]
            path = rest[match.start() + 1:]
        else:
            raw_host, sep, path = rest, "", ""
        host = valid_domain(raw_host)
        if not host:
            return None
        if sep == "*":
            trigger["url-filter"] = host_regex(host) + ".*" + path_regex(path)
        elif sep == "?":
            trigger["url-filter"] = host_regex(host) + ".*\\?" + path_regex(path)
        elif sep == "/":
            trigger["url-filter"] = host_regex(host) + path_regex(path)
        elif sep == "^":
            # host_regex already ends in `[:/]`; trim one leading slash so we
            # do not require `//` when a list writes `||host^/path`.
            if path.startswith("/"):
                path = path[1:]
            trigger["url-filter"] = host_regex(host) + path_regex(path)
        else:
            trigger["url-filter"] = host_regex(host)
    elif body.startswith("|"):
        trigger["url-filter"] = "^" + path_regex(body[1:])
    elif "/" in body or "*" in body:
        try:
            trigger["url-filter"] = path_regex(body.lstrip("*"))
        except re.error:
            return None
    else:
        return None

    try:
        re.compile(trigger["url-filter"])
    except re.error:
        return None
    if not no_disjunction(trigger["url-filter"]):
        return None
    # WebKit content blockers accept ASCII url-filter patterns only.
    if not trigger["url-filter"].isascii():
        return None

    kinds = []
    for name, code in RESOURCE_TYPES.items():
        positive, _ = options.get(name, (False, ""))
        if positive and code not in kinds:
            kinds.append(code)
    if kinds:
        trigger["resource-type"] = kinds

    if options.get("third-party", (False, ""))[0] or options.get("3p", (False, ""))[0]:
        trigger["load-type"] = ["third-party"]
    elif (
        ("third-party" in options and not options["third-party"][0])
        or ("3p" in options and not options["3p"][0])
        or options.get("1p", (False, ""))[0]
    ):
        trigger["load-type"] = ["first-party"]

    if options.get("match-case", (False, ""))[0]:
        trigger["url-filter-is-case-sensitive"] = True

    positive, value = options.get("domain", (False, ""))
    if "domain" in options:
        if not positive or not value:
            return None
        pos_domains, neg_domains = [], []
        for raw in value.split("|"):
            raw = raw.strip()
            if not raw:
                continue
            is_neg = raw.startswith("~")
            dom = valid_domain(raw[1:] if is_neg else raw)
            if not dom:
                return None
            (neg_domains if is_neg else pos_domains).append(f"*{dom}")
        if pos_domains and neg_domains:
            # WebKit forbids both if-domain and unless-domain on one trigger.
            return None
        if pos_domains:
            if len(pos_domains) > 40:
                return None
            trigger["if-domain"] = pos_domains
        elif neg_domains:
            if len(neg_domains) > 40:
                return None
            trigger["unless-domain"] = neg_domains
        else:
            return None

    # A rule with no host, path separator or resource type is a bare word that
    # matches everywhere: too broad to trust, and the lists do not mean it.
    if trigger["url-filter"] in ("", ".*", "^"):
        return None
    return {"trigger": trigger, "action": {"type": "block"}}


def cosmetic_rule(line):
    """One global `##selector` or domain-scoped `example.com##selector` rule."""
    if "#@#" in line or "#?#" in line or "#$#" in line:
        return None
    if "##" not in line:
        return None
    left, _, selector = line.partition("##")
    selector = selector.strip()
    if not selector or len(selector) > 400 or not selector.isascii():
        return None
    # Procedural selectors (:has-text, :xpath, :style) are uBlock's own syntax
    # and mean nothing to a browser engine.
    if re.search(r":(has-text|xpath|style|matches-css|matches-attr|upward|remove)\(", selector):
        return None
    if "{" in selector or "}" in selector:
        return None
    if not left:
        return ((), selector)
    domains = []
    for part in left.split(","):
        part = part.strip()
        if not part:
            continue
        # Never turn a negated or wildcard domain rule into a global hide rule.
        if part.startswith("~") or "*" in part or "?" in part:
            return None
        dom = valid_domain(part)
        if not dom:
            return None
        domains.append(f"*{dom}")
    if not domains or len(domains) > 40:
        return None
    return (tuple(sorted(set(domains))), selector)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cached", action="store_true", help="build from /tmp copies")
    args = parser.parse_args()

    # Both lists are read line by line in step, so neither can be crowded out
    # by the other: EasyPrivacy is the one that blocks trackers, and it is
    # shorter, so draining EasyList first silently dropped all of it.
    network, global_cosmetic = [], []
    scoped_cosmetic = {}
    seen_network, seen_cosmetic = set(), set()
    scoped_count = 0
    counts = {name: 0 for name in LISTS}
    readers = [(name, fetch(name, url, args.cached).splitlines()) for name, url in LISTS.items()]
    longest = max(len(lines) for _, lines in readers)
    for line_number in range(longest):
        for name, lines in readers:
            if line_number >= len(lines):
                continue
            line = lines[line_number].strip()
            if not line or line[0] in "!" or line.startswith("["):
                continue
            if line.startswith("#") and "##" not in line:
                continue
            if "##" in line or "#@#" in line or "#?#" in line:
                parsed = cosmetic_rule(line)
                if parsed is None:
                    continue
                domains, selector = parsed
                if not domains:
                    if len(global_cosmetic) >= MAX_COSMETIC:
                        continue
                    key = ("", selector)
                    if key in seen_cosmetic:
                        continue
                    seen_cosmetic.add(key)
                    global_cosmetic.append(selector)
                    counts[name] += 1
                else:
                    if scoped_count >= MAX_COSMETIC:
                        continue
                    key = (domains, selector)
                    if key in seen_cosmetic:
                        continue
                    seen_cosmetic.add(key)
                    scoped_cosmetic.setdefault(domains, []).append(selector)
                    scoped_count += 1
                    counts[name] += 1
                continue
            rule = network_rule(line)
            if rule is None or len(network) >= MAX_NETWORK:
                continue
            key = json.dumps(rule, sort_keys=True)
            if key in seen_network:
                continue
            seen_network.add(key)
            network.append(rule)
            counts[name] += 1

    # Selector lists are capped, so they go out in chunks. Only genuinely global
    # cosmetic rules go into the global list; site-specific rules keep their
    # `if-domain` trigger so they can never hide unrelated elements elsewhere.
    selectors, total = [ALWAYS_HIDDEN], len(ALWAYS_HIDDEN)
    for piece in global_cosmetic:
        if total + len(piece) > SELECTOR_BUDGET:
            break
        total += len(piece) + 2
        selectors.append(piece)
    chunks = [selectors[i : i + 4000] for i in range(0, len(selectors), 4000)]

    site_rules = []
    for domains, group in scoped_cosmetic.items():
        site_rules.append(
            {
                "trigger": {"url-filter": ".*", "if-domain": list(domains)},
                "action": {"type": "css-display-none", "selector": ", ".join(group)},
            }
        )

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.json"):
        old.unlink()

    def write(name, rules):
        path = OUT / name
        path.write_text(json.dumps(rules, indent=0, separators=(",", ":")))
        return path.stat().st_size

    names = ["network.json"]
    sizes = {"network": write("network.json", network)}
    for index, chunk in enumerate(chunks):
        rule = {
            "trigger": {"url-filter": ".*"},
            "action": {"type": "css-display-none", "selector": ", ".join(chunk)},
        }
        name = f"hide-{index}.json"
        names.append(name)
        sizes[f"hide-{index}"] = write(name, [rule])
    if site_rules:
        names.append("hide-sites.json")
        sizes["hide-sites"] = write("hide-sites.json", site_rules)

    # The browser embeds these, so it needs the list of names at compile time.
    # Generated rather than hand-written, so a new hide list cannot be missed.
    entries = "\n".join(
        f'    include_str!("../assets/shield/{name}"),' for name in names
    )
    (ROOT / "src" / "shield_assets.rs").write_text(
        "// Generated by tools/build_shield.py. Do not edit: run the tool.\n"
        "//\n"
        "// The filter lists, embedded so a build needs no network and no data\n"
        "// files beside the binary.\n"
        "pub const FILTERS: &[&str] = &[\n" + entries + "\n];\n"
    )
    (OUT / "README.md").write_text("\n".join(LICENCE) + "\n")

    rules = sum(len(json.loads((OUT / f"{n}.json").read_text())) for n in sizes)
    # The engine's parser is the only judge that matters, so the count that
    # says "these will work" is a compile, not a line count.
    checker = ROOT / "tools" / "check_shield.py"
    print(f"network rules  {len(network)}")
    print(f"hidden elements {len(selectors)} selectors in {len(chunks)} lists")
    print(f"files            {len(sizes)} in {OUT.relative_to(ROOT)}, {sum(sizes.values()) // 1024} KB")
    for name, kept in counts.items():
        print(f"  from {name:<12} {kept} rules kept")
    return 0


if __name__ == "__main__":
    sys.exit(main())
